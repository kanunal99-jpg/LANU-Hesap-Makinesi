package com.example.core.messaging

import android.content.Context
import androidx.annotation.Keep
import androidx.work.BackoffPolicy
import androidx.work.Constraints
import androidx.work.CoroutineWorker
import androidx.work.ExistingWorkPolicy
import android.os.Build
import androidx.work.OutOfQuotaPolicy
import androidx.work.NetworkType
import androidx.work.OneTimeWorkRequestBuilder
import androidx.work.WorkManager
import androidx.work.WorkerParameters
import com.example.LanuApplication
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.withTimeout
import kotlinx.coroutines.TimeoutCancellationException
import android.database.sqlite.SQLiteDatabaseLockedException
import android.database.sqlite.SQLiteException
import java.security.GeneralSecurityException
import androidx.work.workDataOf
import com.example.core.diagnostics.PrivateRelayHealth
import java.io.IOException
import java.util.concurrent.TimeUnit

/**
 * A consented, opaque FCM hint wakes a bounded E2EE sync without private UI.
 * No sender, message, identity, key, token or wake timestamp enters WorkManager.
 * An absent Keystore identity must NEVER be generated by a background job.
 */
@Keep
class MessageWakeSyncWorker @JvmOverloads constructor(context: Context, params: WorkerParameters,
    private val targetFactory: () -> MessageWakeSyncTarget = {
        val repo = (context.applicationContext as LanuApplication).container.communicationRepository
        object : MessageWakeSyncTarget {
            override val configured get() = repo.relayConfigured
            override suspend fun hasStoredIdentity() = repo.hasStoredIdentity()
            override suspend fun synchronize() = repo.synchronize(activeConversationId = null, requireExistingIdentity = true)
            override suspend fun hasPendingPage() = repo.hasPendingInboxPage()
        }
    }) : CoroutineWorker(context, params) {
    override suspend fun doWork(): Result {
        if (!MessageWakePreferences.isEnabled(applicationContext)) return Result.success()
        return try {
            val repository = targetFactory()
            if (!repository.configured || !repository.hasStoredIdentity() ||
                !MessageWakePreferences.isEnabled(applicationContext)) return Result.success()
            // No active conversation means NO remote read receipts. Existing
            // encrypted Room queue, peer binding, ACK and idempotent UUIDs are
            // reused rather than inventing a second message transport.
            withTimeout(90_000L) {
                repeat(3) {
                    try { repository.synchronize() }
                    catch (e: SecurityException) { if (!repository.hasPendingPage()) throw e }
                    if (!repository.hasPendingPage()) return@withTimeout
                }
            }
            if (repository.hasPendingPage()) enqueue(applicationContext)
            Result.success()
        } catch (_: TimeoutCancellationException) {
            transient(0)
        } catch (cancelled: CancellationException) {
            throw cancelled
        } catch (e: RelayException) {
            transient(e.status)
        } catch (_: SQLiteDatabaseLockedException) {
            PrivateRelayHealth.record(PrivateRelayHealth.Outcome.LOCAL_STORAGE)
            transient(0)
        } catch (_: IOException) {
            transient(0)
        } catch (_: GeneralSecurityException) {
            attention(PrivateRelayHealth.Outcome.SECURE_STORAGE)
        } catch (_: SecurityException) {
            attention(PrivateRelayHealth.Outcome.SECURE_STORAGE)
        } catch (_: SQLiteException) {
            attention(PrivateRelayHealth.Outcome.LOCAL_STORAGE)
        } catch (_: Exception) {
            attention(PrivateRelayHealth.Outcome.RESPONSE)
        }
    }

    private fun transient(status: Int): Result =
        if (MessageWakeSyncPolicy.shouldRetry(MessageWakePreferences.isEnabled(applicationContext), status, runAttemptCount)) Result.retry()
        else Result.success(workDataOf("sync_outcome" to "retry_exhausted_or_blocked"))

    private fun attention(reason: PrivateRelayHealth.Outcome): Result {
        PrivateRelayHealth.record(reason)
        // A handled failure must not cancel unrelated jobs in the APPEND chain.
        // Fixed output explicitly distinguishes completion from successful sync.
        return Result.success(workDataOf("sync_outcome" to "needs_attention", "sync_reason" to reason.name))
    }

    companion object {
        // Append a follow-up: KEEP drops a new hint while the current sync
        // has already taken its inbox snapshot. REPLACE could cancel a commit.
        internal const val UNIQUE = "lanu-private-message-wake-sync-v1"

        fun enqueue(context: Context): Boolean {
            if (!MessageWakePreferences.isEnabled(context)) return false
            return try {
                val builder = OneTimeWorkRequestBuilder<MessageWakeSyncWorker>()
                    .setConstraints(Constraints.Builder()
                        .setRequiredNetworkType(NetworkType.CONNECTED).build())
                    .setBackoffCriteria(BackoffPolicy.EXPONENTIAL, 30, TimeUnit.SECONDS)
                // FCM grants a brief expedited-job exemption on Android 12+.
                // On older devices expedited work would require a foreground
                // service; keep the existing ordinary-job privacy contract.
                if (Build.VERSION.SDK_INT >= 31) builder.setExpedited(
                    OutOfQuotaPolicy.RUN_AS_NON_EXPEDITED_WORK_REQUEST)
                val request = builder.build()
                WorkManager.getInstance(context.applicationContext)
                    .enqueueUniqueWork(UNIQUE, ExistingWorkPolicy.APPEND_OR_REPLACE, request)
                true
            } catch (_: Exception) { false }
        }

        fun cancel(context: Context) {
            try {
                WorkManager.getInstance(context.applicationContext).cancelUniqueWork(UNIQUE)
            } catch (_: Exception) { /* Persisted opt-out remains authoritative. */ }
        }
    }
}

/** Pure policy; no FCM token or private content ever participates in decisions. */
internal object MessageWakeSyncPolicy {
    fun shouldSchedule(consented: Boolean, validWake: Boolean): Boolean =
        consented && validWake

    fun shouldRetry(consented: Boolean, status: Int, attempt: Int): Boolean =
        consented && attempt in 0..1 &&
            (status == 0 || status == 408 || status == 429 || status in 500..599)
}

/** Injectable only in-process; never persisted in WorkManager input. */
interface MessageWakeSyncTarget {
    val configured: Boolean
    suspend fun hasStoredIdentity(): Boolean
    suspend fun synchronize()
    suspend fun hasPendingPage(): Boolean
}
