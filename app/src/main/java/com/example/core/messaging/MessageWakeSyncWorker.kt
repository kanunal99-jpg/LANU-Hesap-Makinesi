package com.example.core.messaging

import android.content.Context
import androidx.annotation.Keep
import androidx.work.BackoffPolicy
import androidx.work.Constraints
import androidx.work.CoroutineWorker
import androidx.work.ExistingWorkPolicy
import androidx.work.NetworkType
import androidx.work.OneTimeWorkRequestBuilder
import androidx.work.WorkManager
import androidx.work.WorkerParameters
import com.example.LanuApplication
import kotlinx.coroutines.CancellationException
import java.io.IOException
import java.util.concurrent.TimeUnit

/**
 * A consented, opaque FCM hint wakes a bounded E2EE sync without private UI.
 * No sender, message, identity, key, token or wake timestamp enters WorkManager.
 * An absent Keystore identity must NEVER be generated by a background job.
 */
@Keep
class MessageWakeSyncWorker(context: Context, params: WorkerParameters) :
    CoroutineWorker(context, params) {
    override suspend fun doWork(): Result {
        if (!MessageWakePreferences.isEnabled(applicationContext)) return Result.success()
        return try {
            val repository = (applicationContext as LanuApplication).container.communicationRepository
            if (!repository.relayConfigured || !repository.hasStoredIdentity() ||
                !MessageWakePreferences.isEnabled(applicationContext)) return Result.success()
            // No active conversation means NO remote read receipts. Existing
            // encrypted Room queue, peer binding, ACK and idempotent UUIDs are
            // reused rather than inventing a second message transport.
            repository.synchronize(activeConversationId = null, requireExistingIdentity = true)
            Result.success()
        } catch (cancelled: CancellationException) {
            throw cancelled
        } catch (e: RelayException) {
            if (MessageWakeSyncPolicy.shouldRetry(
                    MessageWakePreferences.isEnabled(applicationContext),
                    e.status, runAttemptCount)) Result.retry() else Result.success()
        } catch (_: IOException) {
            if (MessageWakeSyncPolicy.shouldRetry(
                    MessageWakePreferences.isEnabled(applicationContext),
                    0, runAttemptCount)) Result.retry() else Result.success()
        } catch (_: Exception) {
            // No exception text or private payload in WorkManager output/logs.
            // Foreground/manual sync remains the fallback.
            Result.success()
        }
    }

    companion object {
        private const val UNIQUE = "lanu-private-message-wake-sync-v1"

        fun enqueue(context: Context): Boolean {
            if (!MessageWakePreferences.isEnabled(context)) return false
            return try {
                val request = OneTimeWorkRequestBuilder<MessageWakeSyncWorker>()
                    .setConstraints(Constraints.Builder()
                        .setRequiredNetworkType(NetworkType.CONNECTED).build())
                    .setBackoffCriteria(BackoffPolicy.EXPONENTIAL, 30, TimeUnit.SECONDS)
                    .build()
                WorkManager.getInstance(context.applicationContext)
                    .enqueueUniqueWork(UNIQUE, ExistingWorkPolicy.KEEP, request)
                true
            } catch (_: Exception) { false }
        }

        fun cancel(context: Context) {
            try {
                WorkManager.getInstance(context.applicationContext).cancelUniqueWork(UNIQUE)
            } catch (_: Exception) { /* Persisted opt-out remains authoritative. */ }
        }
    }
}

/** Pure policy; no FCM token or private content ever participates in decisions. */
internal object MessageWakeSyncPolicy {
    fun shouldSchedule(consented: Boolean, validWake: Boolean): Boolean =
        consented && validWake

    fun shouldRetry(consented: Boolean, status: Int, attempt: Int): Boolean =
        consented && attempt in 0..1 &&
            (status == 0 || status == 408 || status == 429 || status in 500..599)
}
